#!/usr/bin/env python3
"""Generate src/cars.inc from the game's own data:
   - car ids:   VEHICLES/VEH_<id>_HI.BNDL file names
   - classes:   VEHICLES/VEHICLELIST.BNDL (class collection key at entry+0x18)
   - names:     UI/LANGUAGE/0001.BNDL (English) via the name id at entry+0x08
Usage: gen_cars.py "<game folder>" > src/cars.inc"""
import os, re, sys, zlib, struct

def inflate_bundle(path):
    b = open(path, "rb").read(); out = b""; i = 0
    while True:
        js = [x for x in (b.find(b"\x78\xda", i), b.find(b"\x78\x9c", i)) if x != -1]
        if not js: return out
        j = min(js)
        try:
            d = zlib.decompressobj(); r = d.decompress(b[j:])
            if len(r) > 32: out += r; i = j + len(b[j:]) - len(d.unused_data); continue
        except zlib.error: pass
        i = j + 2

def strings(path):
    t = inflate_bundle(path); ver, n, ido, pro = struct.unpack_from("<4I", t)
    ids = struct.unpack_from(f"<{n}I", t, ido); pr = struct.unpack_from(f"<{2*n}I", t, pro)
    return {ids[k]: t[pr[2*k]:pr[2*k] + 2*pr[2*k+1]].decode("utf-16-le", "replace").rstrip("\0").strip() for k in range(n)}

CLASSES = {0x108F58: 0, 0x108F50: 1, 0x108F5F: 2, 0x108F67: 3, 0x108F69: 4, 0x108F66: 5, 0x108F68: 6}
game = sys.argv[1]
names = strings(os.path.join(game, "UI", "LANGUAGE", "0001.BNDL"))
vl = inflate_bundle(os.path.join(game, "VEHICLES", "VEHICLELIST.BNDL"))
ids = sorted({int(m.group(1)) for f in os.listdir(os.path.join(game, "VEHICLES")) if (m := re.match(r"VEH_(\d+)_HI\.BNDL$", f))})
print("// Generated by tools/gen_cars.py from the game's VEHICLELIST and language data. Do not edit.")
print("// { car id, class (0 Sports 1 Muscle 2 Exotic 3 Grand Tourer 4 Everyday 5 SUV 6 Race), name }")
seen = set()
for cid in ids:
    o = vl.find(struct.pack("<I", cid))
    if o < 0: continue
    e = struct.unpack_from("<8I", vl, o)
    cls = CLASSES.get(e[6])
    if cls is None: continue                      # police, special and duplicate variants
    nm = names.get(e[2]) or names.get(e[1]) or f"Car {cid}"
    nm = re.sub(r"[-™]", "", nm).strip()
    if (nm, cls) in seen and cid > 1400000: continue  # skip promo duplicates of the same car
    seen.add((nm, cls))
    print(f'  {{{cid}, {cls}, "{nm}"}},')
